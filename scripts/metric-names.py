#!/usr/bin/env python3
"""Maintain the inventory of Prometheus metric names exported through the `metrics` crate.

Alert rules and dashboards, ours and node operators', query these names
directly, so a rename or removal silently turns an alert into a query with no
data. CI runs `--check` to fail when the source and the inventory disagree;
regenerate it with `--write` and call out removed or renamed metrics in the
release notes.
"""

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INVENTORY = ROOT / "docs" / "metric-names.txt"
SOURCE_DIRS = ("bin", "crates")
SKIP_DIRS = {"target", "tests", "benches", "examples", "testdata"}
SKIP_FILES = {"tests.rs", "test_utils.rs"}
# Reth's Prometheus recorder prefixes every metric name.
PREFIX = "reth_"
# Binaries that install their own recorder without that prefix.
UNPREFIXED: tuple[str, ...] = ()
KINDS = {"Counter": "counter", "Gauge": "gauge", "Histogram": "histogram"}
# Files that build metric names at runtime, so their names cannot be read from
# the source. Keep this short: prefer string literals.
UNTRACKED = {
    # Database metrics are reported through `DatabaseMetrics` with names from
    # `gauge_metrics` and friends; `describe_*!` calls in reth-node-metrics name them.
    "crates/storage/db-api/src/database_metrics.rs",
    "crates/storage/db/src/implementation/mdbx/mod.rs",
}

HEADER = """\
# Prometheus metric names exported through the `metrics` crate, generated by
# `scripts/metric-names.py --write`. Histograms are exported as summaries with
# `_count`, `_sum` and `quantile` series. `<dynamic>` stands for a scope chosen
# at runtime.
#
# Alerts and dashboards, ours and node operators', query these names. When a
# name is removed or renamed here, say so in the release notes.
"""

MACRO = re.compile(r"(?<![\w])(counter|gauge|histogram)!\s*\(\s*")
DESCRIBE = re.compile(r'(?<![\w])describe_(counter|gauge|histogram)!\s*\(\s*"([^"\\]+)"')
METRICS_ATTR = re.compile(r"#\[metrics\(([^)]*)\)\]")
STRUCT = re.compile(r"\bstruct\s+\w+\s*(?:<[^{]*>)?\s*\{")
FIELD = re.compile(
    r"((?:#\[[^\]]*\]\s*)*)(?:pub(?:\([^)]*\))?\s+)?(\w+)\s*:\s*([\w:]+(?:<[^>]*>)?)\s*,?"
)
RENAME = re.compile(r'#\[metric\([^\]]*rename\s*=\s*"([^"]+)"')
TEST_MOD = re.compile(r"#\[cfg\(test\)\]\s*(?:pub(?:\([^)]*\))?\s+)?mod\s+\w+\s*\{")
INVALID = re.compile(r"[^a-zA-Z0-9_:]")
LITERAL = re.compile(r'r(#*)".*?"\1|"(?:\\.|[^"\\])*"|' + r"'(?:\\.|[^\\'])'", re.S)


def sanitize(name: str) -> str:
    """Apply the Prometheus exporter's name sanitization."""
    return INVALID.sub("_", name)


def strip_comments(src: str) -> str:
    """Blank out comments while keeping string literals and line numbers intact."""
    out = []
    i, n = 0, len(src)
    while i < n:
        c = src[i]
        if src.startswith("//", i):
            end = src.find("\n", i)
            end = n if end == -1 else end
            i = end
        elif src.startswith("/*", i):
            depth, j = 1, i + 2
            while j < n and depth:
                if src.startswith("/*", j):
                    depth, j = depth + 1, j + 2
                elif src.startswith("*/", j):
                    depth, j = depth - 1, j + 2
                else:
                    j += 1
            out.append("\n" * src.count("\n", i, j))
            i = j
        elif (m := re.match(r'r(#*)"', src[i : i + 8])) and (i == 0 or not (src[i - 1].isalnum() or src[i - 1] == "_")):
            close = '"' + m.group(1)
            end = src.find(close, i + len(m.group(0)))
            end = n if end == -1 else end + len(close)
            out.append(src[i:end])
            i = end
        elif c == '"':
            j = i + 1
            while j < n and src[j] != '"':
                j += 2 if src[j] == "\\" else 1
            out.append(src[i : j + 1])
            i = j + 1
        elif c == "'" and (m := re.match(r"'(?:\\.|\\u\{[0-9a-fA-F]+\}|[^\\'])'", src[i : i + 12])):
            out.append(m.group(0))
            i += len(m.group(0))
        else:
            out.append(c)
            i += 1
    return "".join(out)


def mask_literals(src: str) -> str:
    """Blank the contents of string and char literals, keeping offsets, so braces in them do not count."""
    def blank(m: re.Match) -> str:
        s = m.group(0)
        start = min(s.find(c) for c in "\"'" if c in s)
        end = max(s.rfind(c) for c in "\"'")
        return s[: start + 1] + re.sub(r"[^\n]", " ", s[start + 1 : end]) + s[end:]

    return LITERAL.sub(blank, src)


def matching_brace(masked: str, open_idx: int) -> int:
    depth = 0
    for j in range(open_idx, len(masked)):
        if masked[j] == "{":
            depth += 1
        elif masked[j] == "}":
            depth -= 1
            if depth == 0:
                return j
    raise ValueError("unbalanced braces")


def line_of(src: str, idx: int) -> int:
    return src.count("\n", 0, idx) + 1


def collect(path: Path, metrics: dict[str, set[str]], errors: list[str]) -> None:
    text = path.read_text()
    if "metrics" not in text and not MACRO.search(text):
        return
    src = strip_comments(text)
    masked = mask_literals(src)
    # Metrics declared in test modules are never exported.
    for test_mod in reversed(list(TEST_MOD.finditer(masked))):
        start, end = test_mod.start(), matching_brace(masked, test_mod.end() - 1) + 1
        blank = re.sub(r"[^\n]", " ", src[start:end])
        src, masked = src[:start] + blank + src[end:], masked[:start] + blank + masked[end:]
    rel = path.relative_to(ROOT).as_posix()
    prefix = "" if rel.startswith(UNPREFIXED) else PREFIX

    for attr in METRICS_ATTR.finditer(masked):
        where = f"{rel}:{line_of(src, attr.start())}"
        args = src[attr.start(1) : attr.end(1)]
        scope = re.search(r'scope\s*=\s*"([^"]+)"', args)
        separator = re.search(r'separator\s*=\s*"([^"]*)"', args)
        dynamic = re.search(r"dynamic\s*=\s*true", args)
        if not scope and not dynamic:
            errors.append(f"{where}: `#[metrics(...)]` needs a static `scope` or `dynamic = true`")
            continue
        struct = STRUCT.search(masked, attr.end())
        if not struct:
            errors.append(f"{where}: no struct follows the metrics attribute")
            continue
        open_idx = struct.end() - 1
        body = src[open_idx + 1 : matching_brace(masked, open_idx)]
        sep = separator.group(1) if separator else "_"
        for field in FIELD.finditer(body):
            attrs, name, ty = field.groups()
            if "#[metric(skip" in attrs.replace(" ", ""):
                continue
            kind = KINDS.get(ty.split("<", 1)[0].rsplit("::", 1)[-1])
            if kind is None:
                errors.append(f"{where}: field `{name}` has unsupported metric type `{ty}`")
                continue
            rename = RENAME.search(attrs)
            suffix = sanitize(f"{sep}{rename.group(1) if rename else name}")
            full = "<dynamic>" + suffix if dynamic else prefix + sanitize(scope.group(1)) + suffix
            metrics.setdefault(full, set()).add(kind)

    for call in MACRO.finditer(masked):
        literal = re.match(r'"([^"\\]+)"', src[call.end() :])
        if not literal:
            if rel not in UNTRACKED:
                errors.append(
                    f"{rel}:{line_of(src, call.start())}: `{call.group(1)}!` needs a string literal name "
                    "so the metric inventory can track it, or its file must be listed in UNTRACKED"
                )
            continue
        metrics.setdefault(prefix + sanitize(literal.group(1)), set()).add(call.group(1))

    # Names passed to the macros at runtime are often described up front.
    for described in DESCRIBE.finditer(src):
        metrics.setdefault(prefix + sanitize(described.group(2)), set()).add(described.group(1))


def render() -> str:
    metrics: dict[str, set[str]] = {}
    errors: list[str] = []
    for directory in SOURCE_DIRS:
        for path in sorted((ROOT / directory).rglob("*.rs")):
            parts = path.relative_to(ROOT).parts
            if SKIP_DIRS.intersection(parts) or path.name in SKIP_FILES:
                continue
            collect(path, metrics, errors)
    if errors:
        sys.exit("error: " + "\nerror: ".join(errors))
    for name, kinds in metrics.items():
        if len(kinds) > 1:
            sys.exit(f"error: {name} is registered as more than one kind: {', '.join(sorted(kinds))}")
    lines = [f"{name} {next(iter(kinds))}" for name, kinds in sorted(metrics.items())]
    return HEADER + "\n" + "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="fail if the inventory is stale")
    mode.add_argument("--write", action="store_true", help="regenerate the inventory")
    args = parser.parse_args()

    rendered = render()
    if args.write:
        INVENTORY.write_text(rendered)
        return

    current = INVENTORY.read_text() if INVENTORY.exists() else ""
    if current == rendered:
        return

    def names(text: str) -> set[str]:
        return {line.split()[0] for line in text.splitlines() if line and not line.startswith("#")}

    old, new = names(current), names(rendered)
    for name in sorted(old - new):
        print(f"removed: {name}")
    for name in sorted(new - old):
        print(f"added:   {name}")
    sys.exit(
        f"{INVENTORY.relative_to(ROOT)} is out of date. Run `scripts/metric-names.py --write`, commit the "
        "result, and note removed or renamed metrics in the release notes."
    )


if __name__ == "__main__":
    main()
